"""
ETL: Copy current pipeline snapshot → past_pipeline (before weekly CSV overwrite).
Called at the START of each pipeline upload from etl_pipeline.run_multi().
"""
from datetime import date
from utils import get_conn, get_logger, snap_week

log = get_logger("etl.past_pipeline")

_DDL_TABLE = """
CREATE TABLE past_pipeline (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id NVARCHAR(50),
    account_name NVARCHAR(500),
    region_lvl3 NVARCHAR(200),
    region_lvl4 NVARCHAR(200),
    solution_area_l1 NVARCHAR(200),
    sub_solution_area_l2 NVARCHAR(200),
    closing_qtr NVARCHAR(20),
    fc_qualification NVARCHAR(100),
    drm_category NVARCHAR(100),
    opp_phase NVARCHAR(100),
    engagement_type NVARCHAR(100),
    deal_qualification_score NVARCHAR(50),
    acv_usd DECIMAL(18,2),
    deal_qualification_decision NVARCHAR(100),
    age_days INTEGER,
    dda_status NVARCHAR(100),
    vat_dh NCLOB,
    opp_owner_name NVARCHAR(200),
    snapshot_week DATE,
    captured_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
)
"""

_DDL_INDEX = (
    "CREATE INDEX past_pipeline_snap_opp ON past_pipeline(snapshot_week, opportunity_id)"
)


def _ensure_table():
    with get_conn() as conn:
        cur = conn.cursor()
        try:
            cur.execute(_DDL_TABLE.strip())
            log.info("past_pipeline table created")
        except Exception:
            pass
        try:
            cur.execute(_DDL_INDEX)
            log.info("past_pipeline index created")
        except Exception:
            pass


def _is_first_monday_of_quarter(today: date) -> bool:
    return today.month in (1, 4, 7, 10) and today.weekday() == 0 and today.day <= 7


def run() -> int:
    _ensure_table()

    today = snap_week()

    with get_conn() as conn:
        cur = conn.cursor()

        # Idempotent: skip if this snapshot_week already exists
        cur.execute("SELECT COUNT(*) FROM past_pipeline WHERE snapshot_week = ?", [today])
        if cur.fetchone()[0] > 0:
            log.info("past_pipeline snapshot %s already exists, skipping", today)
            return 0

        if _is_first_monday_of_quarter(today):
            log.info("First Monday of quarter (%s) — truncating past_pipeline", today)
            cur.execute("TRUNCATE TABLE past_pipeline")

        cur.execute("""
            INSERT INTO past_pipeline (
                opportunity_id, account_name, region_lvl3, region_lvl4,
                solution_area_l1, sub_solution_area_l2, closing_qtr, fc_qualification,
                drm_category, opp_phase, engagement_type, deal_qualification_score,
                acv_usd, deal_qualification_decision, age_days,
                dda_status, vat_dh, opp_owner_name, snapshot_week
            )
            SELECT
                p.opportunity_id, p.account_name, p.region_lvl3, p.region_lvl4,
                p.solution_area_l1, p.sub_solution_area_l2, p.closing_qtr, p.fc_qualification,
                p.drm_category, p.opp_phase, p.engagement_type, p.deal_qualification_score,
                p.acv_usd, p.deal_qualification_decision, p.age_days,
                d.dda_status, p.vat_dh, p.opp_owner_name, p.snapshot_week
            FROM pipeline p
            LEFT JOIN dda d ON d.opp_id = p.opportunity_id
            WHERE p.snapshot_week = (SELECT MAX(snapshot_week) FROM pipeline)
        """)
        n = cur.rowcount
        log.info("past_pipeline: %d rows copied for snapshot_week %s", n, today)
        return n


if __name__ == "__main__":
    print(run())
